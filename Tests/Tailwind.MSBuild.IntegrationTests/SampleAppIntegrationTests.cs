namespace Tailwind.MSBuild.IntegrationTests;

using System.Globalization;
using System.Threading;
using System.Xml.Linq;
using FluentAssertions;
using Tailwind.MSBuild.Tasks;
using Xunit;

public sealed class SampleAppIntegrationTests : IDisposable
{
    private const string FakeCliVersion = "test-version";
    private const string FakeCliOutput = "/* generated by fake tailwind cli */";
    private readonly List<string> tempDirectories = [];

    [Theory]
    [InlineData(null, false, "false")]
    [InlineData("0", false, "false")]
    [InlineData("1", false, "true")]
    [InlineData("true", false, "true")]
    [InlineData("1", true, "false")]
    public void EvaluateSampleApp_ResolvesTailwindWatch(string? dotNetWatch, bool disableWatch, string expected)
    {
        var context = CreateIsolatedSampleApp();
        var overrideArgument = disableWatch ? " -p:TailwindWatch=false" : string.Empty;

        var result = RunProcess(
            "dotnet",
            $"msbuild {Quote(context.SampleProjectPath)} -getProperty:TailwindWatch{overrideArgument}",
            context.SampleDirectory,
            new Dictionary<string, string?>
            {
                ["DOTNET_WATCH"] = dotNetWatch,
                ["DotNetWatchBuild"] = null,
                ["BuildingInsideVisualStudio"] = null,
                ["TailwindWatch"] = null
            });

        result.ExitCode.Should().Be(0, "TailwindWatch evaluation should succeed. StdOut: {0}{1}StdErr: {2}", Environment.NewLine, result.StandardOutput, result.StandardError);

        result.StandardOutput.Trim().Should().Be(expected);
    }

    [Fact]
    public void ListSampleAppWatchFiles_DoesNotRunTailwind()
    {
        var context = CreateIsolatedSampleApp();
        var result = RunProcess("dotnet", "watch --list", context.SampleDirectory);

        result.ExitCode.Should().Be(0, "watch list should succeed. StdOut: {0}{1}StdErr: {2}", Environment.NewLine, result.StandardOutput, result.StandardError);
        result.StandardOutput.Should().Contain("Program.cs");
        File.Exists(GetInputCssPath(context)).Should().BeFalse();
        File.Exists(GetOutputCssPath(context)).Should().BeFalse();
    }

    [Theory]
    [InlineData(true)]
    [InlineData(false)]
    public void WatchRunSampleApp_RespectsTailwindWatchOptOut(bool expectWatcher)
    {
        var context = CreateIsolatedSampleApp();
        SeedCachedTailwindBinary(context.CliCacheRoot);

        var appReady = Path.Combine(context.CliCacheRoot, "app.ready");
        var cliReady = Path.Combine(context.CliCacheRoot, "watch.ready");
        var cliStop = Path.Combine(context.CliCacheRoot, "watch.stop");
        var project = XDocument.Load(context.SampleProjectPath);
        var settings = new XElement("PropertyGroup",
            new XElement("ImplicitUsings", "enable"),
            new XElement("TailwindMSBuildAssembly", context.TaskAssemblyPath),
            new XElement("TailwindInstallPath", context.CliCacheRoot),
            new XElement("TailwindVersion", FakeCliVersion));
        if (!expectWatcher)
            settings.Add(new XElement("TailwindWatch", "false"));
        project.Root!.Elements("Import").First().AddBeforeSelf(settings);
        project.Save(context.SampleProjectPath);

        // Exercise the real watch host without depending on Kestrel ports or browser startup.
        File.WriteAllText(Path.Combine(context.SampleDirectory, "Program.cs"), """
            File.WriteAllText(Environment.GetEnvironmentVariable("TAILWIND_TEST_APP_READY")!, "ready");
            await Task.Delay(Timeout.InfiniteTimeSpan);
            """);

        try
        {
            var result = RunProcess(
                "dotnet", "watch run --no-launch-profile --non-interactive",
                context.SampleDirectory,
                new Dictionary<string, string?>
                {
                    ["DOTNET_ROOT"] = GetDotNetRoot(),
                    ["DOTNET_WATCH"] = null,
                    ["DotNetWatchBuild"] = null,
                    ["BuildingInsideVisualStudio"] = null,
                    ["TailwindWatch"] = null,
                    ["DOTNET_WATCH_SUPPRESS_LAUNCH_BROWSER"] = "1",
                    ["DISPLAY"] = null,
                    ["WAYLAND_DISPLAY"] = null,
                    ["TailwindTerminalExecutable"] = null,
                    ["TAILWIND_TEST_CLI_EXIT_CODE"] = "0",
                    ["TAILWIND_TEST_CLI_WRITE_OUTPUT"] = "1",
                    ["TAILWIND_TEST_APP_READY"] = appReady,
                    ["TAILWIND_TEST_CLI_READY"] = cliReady,
                    ["TAILWIND_TEST_CLI_STOP"] = cliStop
                },
                stopWhen: () => File.Exists(appReady) && (!expectWatcher || File.Exists(cliReady)));

            File.Exists(appReady).Should().BeTrue("dotnet watch should start the app. StdOut: {0}{1}StdErr: {2}",
                result.StandardOutput, Environment.NewLine, result.StandardError);
            File.ReadAllText(GetOutputCssPath(context)).Should().Be(FakeCliOutput);
            File.Exists(cliReady).Should().Be(expectWatcher);

            var lockFilePath = Path.Combine(context.SampleDirectory, "obj", "tailwind-cli", "watch.lock");
            File.Exists(lockFilePath).Should().Be(expectWatcher);
            if (expectWatcher)
            {
                using var watchLock = JsonDocument.Parse(File.ReadAllText(lockFilePath));
                var cliPid = int.Parse(File.ReadAllText(cliReady), CultureInfo.InvariantCulture);
                watchLock.RootElement.EnumerateArray().Single().GetProperty("pid").GetInt32().Should().Be(cliPid);
            }
        }
        finally
        {
            File.WriteAllText(cliStop, "stop");
        }
    }

    [Fact]
    public void BuildSampleApp_UsesMsBuildTasksAndGeneratesDefaultInputFile()
    {
        var context = CreateIsolatedSampleApp();
        var result = BuildSampleApp(context, exitCode: 0, writeOutput: true);

        result.ExitCode.Should().Be(
            0,
            "sample build should succeed with Tailwind.MSBuild tasks enabled. StdOut: {0}{1}StdErr: {2}",
            Environment.NewLine,
            result.StandardOutput,
            result.StandardError);

        var inputCss = File.ReadAllText(GetInputCssPath(context));
        inputCss.Should().Contain("@import \"tailwindcss\";");
        inputCss.Should().Contain("@source \"../\";");

        File.ReadAllText(GetOutputCssPath(context)).Should().Be(FakeCliOutput);

        var lockFilePath = Path.Combine(context.SampleDirectory, "obj", "tailwind-cli", "watch.lock");
        File.Exists(lockFilePath).Should().BeFalse();
    }

    [Theory]
    [InlineData(23, true, "exited with code 23")]
    [InlineData(0, false, "did not generate")]
    public void BuildSampleApp_FailsWhenCliDoesNotProduceASuccessfulResult(int exitCode, bool writeOutput, string expectedError)
    {
        var context = CreateIsolatedSampleApp();
        var result = BuildSampleApp(context, exitCode, writeOutput);

        result.ExitCode.Should().NotBe(0);
        var output = result.StandardOutput + result.StandardError;
        output.Should().Contain(expectedError);
        if (!writeOutput)
            output.Should().Contain("tailwind.css");
    }

    public void Dispose()
    {
        foreach (var directory in this.tempDirectories.OrderByDescending(_ => _.Length))
        {
            try
            {
                if (Directory.Exists(directory))
                    Directory.Delete(directory, recursive: true);
            }
            catch (IOException)
            {
            }
            catch (UnauthorizedAccessException)
            {
            }
        }
    }

    private SampleContext CreateIsolatedSampleApp()
    {
        var repositoryRoot = FindRepositoryRoot();
        var tempRoot = Path.Combine(Path.GetTempPath(), "tailwind-msbuild-integration", Guid.NewGuid().ToString("N"));
        var isolatedRoot = Path.Combine(tempRoot, "sample repo");
        var sampleSource = Path.Combine(repositoryRoot, "Sample", "SampleApp");
        var sampleDestination = Path.Combine(isolatedRoot, "Sample", "SampleApp");
        var buildSource = Path.Combine(repositoryRoot, "Source", "Tailwind.MSBuild", "build");
        var buildDestination = Path.Combine(isolatedRoot, "Source", "Tailwind.MSBuild", "build");
        var cliCacheRoot = Path.Combine(tempRoot, "cli-cache");

        this.tempDirectories.Add(tempRoot);

        CopyDirectory(sampleSource, sampleDestination, IsSampleSource);
        CopyDirectory(buildSource, buildDestination);

        return new SampleContext(
            SampleDirectory: sampleDestination,
            SampleProjectPath: Path.Combine(sampleDestination, "SampleApp.csproj"),
            TaskAssemblyPath: typeof(GetTailwindCLI).Assembly.Location,
            CliCacheRoot: cliCacheRoot);
    }

    private static CommandResult BuildSampleApp(SampleContext context, int exitCode, bool writeOutput)
    {
        SeedCachedTailwindBinary(context.CliCacheRoot);

        var arguments = string.Join(
            " ",
            [
                "build",
                Quote(context.SampleProjectPath),
                "-nologo",
                "-v",
                "minimal",
                $"-p:TailwindMSBuildAssembly={Quote(context.TaskAssemblyPath)}",
                $"-p:TailwindInstallPath={Quote(context.CliCacheRoot)}",
                $"-p:TailwindVersion={FakeCliVersion}",
                "-p:TailwindWatch=false",
                "-p:ImplicitUsings=enable"
            ]);

        return RunProcess("dotnet", arguments, context.SampleDirectory, new Dictionary<string, string?>
        {
            ["DOTNET_ROOT"] = GetDotNetRoot(),
            ["TAILWIND_TEST_CLI_EXIT_CODE"] = exitCode.ToString(CultureInfo.InvariantCulture),
            ["TAILWIND_TEST_CLI_WRITE_OUTPUT"] = writeOutput ? "1" : "0"
        });
    }

    private static string GetInputCssPath(SampleContext context)
        => Path.Combine(context.SampleDirectory, "Styles", "tailwind.input.css");

    private static string GetDotNetRoot()
        => Path.GetFullPath(Path.Combine(RuntimeEnvironment.GetRuntimeDirectory(), "..", "..", ".."));

    private static string GetOutputCssPath(SampleContext context)
        => Path.Combine(context.SampleDirectory, "wwwroot", "css", "tailwind.css");

    private static CommandResult RunProcess(
        string fileName,
        string arguments,
        string workingDirectory,
        IReadOnlyDictionary<string, string?>? environmentVariables = null,
        Func<bool>? stopWhen = null)
    {
        using var process = new Process
        {
            StartInfo = new ProcessStartInfo
            {
                FileName = fileName,
                Arguments = arguments,
                WorkingDirectory = workingDirectory,
                UseShellExecute = false,
                RedirectStandardOutput = true,
                RedirectStandardError = true
            }
        };

        if (environmentVariables != null)
        {
            foreach (var (name, value) in environmentVariables)
            {
                if (value == null)
                    process.StartInfo.Environment.Remove(name);
                else
                    process.StartInfo.Environment[name] = value;
            }
        }

        var standardOutput = new StringBuilder();
        var standardError = new StringBuilder();

        process.OutputDataReceived += (_, eventArgs) =>
        {
            if (eventArgs.Data != null)
                standardOutput.AppendLine(eventArgs.Data);
        };

        process.ErrorDataReceived += (_, eventArgs) =>
        {
            if (eventArgs.Data != null)
                standardError.AppendLine(eventArgs.Data);
        };

        process.Start();
        process.BeginOutputReadLine();
        process.BeginErrorReadLine();

        try
        {
            if (stopWhen == null)
            {
                if (!process.WaitForExit(180000))
                    throw new TimeoutException($"Command timed out: {fileName} {arguments}");
            }
            else
            {
                // Return captured diagnostics on startup failure or timeout, even when
                // the watch process stays alive waiting for changes after a failed build.
                SpinWait.SpinUntil(() => process.HasExited || stopWhen(), TimeSpan.FromSeconds(30));
            }
        }
        finally
        {
            if (!process.HasExited)
                process.Kill(entireProcessTree: true);
        }

        process.WaitForExit();
        return new CommandResult(process.ExitCode, standardOutput.ToString(), standardError.ToString());
    }

    private static void SeedCachedTailwindBinary(string cliCacheRoot)
    {
        var getTailwind = new GetTailwindCLI
        {
            Version = FakeCliVersion,
            RootInstallPath = cliCacheRoot
        };

        // Build a native apphost so MSBuild starts an executable directly on every platform.
        var sourceDirectory = Path.Combine(cliCacheRoot, "fake-cli-source");
        Directory.CreateDirectory(sourceDirectory);
        File.WriteAllText(Path.Combine(sourceDirectory, "NuGet.Config"), "<configuration><packageSources><clear /></packageSources></configuration>");
        File.WriteAllText(Path.Combine(sourceDirectory, "FakeTailwindCli.csproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <OutputType>Exe</OutputType>
                <TargetFramework>net10.0</TargetFramework>
              </PropertyGroup>
            </Project>
            """);
        File.WriteAllText(Path.Combine(sourceDirectory, "Program.cs"), $$"""
            using System;
            using System.Globalization;
            using System.IO;
            using System.Threading;

            if (Environment.GetEnvironmentVariable("TAILWIND_TEST_CLI_WRITE_OUTPUT") == "1")
            {
                var input = args[Array.IndexOf(args, "-i") + 1];
                var output = args[Array.IndexOf(args, "-o") + 1];
                if (!File.Exists(input))
                    return 2;

                Directory.CreateDirectory(Path.GetDirectoryName(output)!);
                File.WriteAllText(output, "{{FakeCliOutput}}");
            }

            var ready = Environment.GetEnvironmentVariable("TAILWIND_TEST_CLI_READY");
            if (ready != null && Array.Exists(args, arg => arg == "--watch" || arg == "--watch=always"))
            {
                File.WriteAllText(ready, Environment.ProcessId.ToString(CultureInfo.InvariantCulture));
                var stop = Environment.GetEnvironmentVariable("TAILWIND_TEST_CLI_STOP");
                SpinWait.SpinUntil(() => File.Exists(stop), TimeSpan.FromSeconds(45));
            }

            return int.Parse(Environment.GetEnvironmentVariable("TAILWIND_TEST_CLI_EXIT_CODE")!, CultureInfo.InvariantCulture);
            """);

        var expectedCliPath = getTailwind.GetFilePath();
        var outputDirectory = Path.GetDirectoryName(expectedCliPath)!;
        var result = RunProcess("dotnet", $"build FakeTailwindCli.csproj --nologo -o {Quote(outputDirectory)}", sourceDirectory);

        result.ExitCode.Should().Be(0, "fake CLI build failed. StdOut: {0}{1}StdErr: {2}", Environment.NewLine, result.StandardOutput, result.StandardError);
        File.Move(Path.Combine(outputDirectory, OperatingSystem.IsWindows() ? "FakeTailwindCli.exe" : "FakeTailwindCli"), expectedCliPath);
    }

    private static bool IsSampleSource(string relativePath)
        => relativePath is not ("bin" or "obj" or "artifacts")
            && relativePath != Path.Combine("Styles", "tailwind.input.css")
            && relativePath != Path.Combine("wwwroot", "css", "tailwind.css");

    private static void CopyDirectory(string sourcePath, string destinationPath, Func<string, bool>? include = null)
    {
        CopyDirectory(new DirectoryInfo(sourcePath), string.Empty);

        void CopyDirectory(DirectoryInfo sourceDirectory, string relativeDirectory)
        {
            Directory.CreateDirectory(Path.Combine(destinationPath, relativeDirectory));

            foreach (var directory in sourceDirectory.EnumerateDirectories())
            {
                var relativePath = Path.Combine(relativeDirectory, directory.Name);
                if (include == null || include(relativePath))
                    CopyDirectory(directory, relativePath);
            }

            foreach (var file in sourceDirectory.EnumerateFiles())
            {
                var relativePath = Path.Combine(relativeDirectory, file.Name);
                if (include == null || include(relativePath))
                    file.CopyTo(Path.Combine(destinationPath, relativePath));
            }
        }
    }

    private static string FindRepositoryRoot()
    {
        var current = new DirectoryInfo(AppContext.BaseDirectory);

        while (current != null)
        {
            var solutionPath = Path.Combine(current.FullName, "Tailwind.MSBuild.sln");

            if (File.Exists(solutionPath))
                return current.FullName;

            current = current.Parent;
        }

        throw new DirectoryNotFoundException("Unable to locate repository root from test runtime directory.");
    }

    private static string Quote(string value)
    {
        return $"\"{value}\"";
    }

    private sealed record SampleContext(
        string SampleDirectory,
        string SampleProjectPath,
        string TaskAssemblyPath,
        string CliCacheRoot);

    private sealed record CommandResult(
        int ExitCode,
        string StandardOutput,
        string StandardError);
}
